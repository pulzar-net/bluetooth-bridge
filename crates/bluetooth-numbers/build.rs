//! Generates the lookup tables from the Bluetooth SIG's Assigned Numbers.
//!
//! The SIG publishes them as YAML in its public repository
//! (<https://bitbucket.org/bluetooth-SIG/public>), checked out here as the git
//! submodule `sig/` and bumped by Dependabot. Nothing in the generated tables is
//! typed by hand: a new company identifier or UUID arrives with the bump.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use yaml_rust2::{Yaml, YamlLoader};

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("sig/assigned_numbers");
    if !root
        .join("company_identifiers/company_identifiers.yaml")
        .exists()
    {
        panic!(
            "the Bluetooth SIG assigned numbers are missing at {}; run `git submodule update --init`",
            root.display()
        );
    }
    println!("cargo:rerun-if-changed={}", root.display());

    let mut out = String::new();
    out.push_str(
        "// Generated by build.rs from the Bluetooth SIG's assigned numbers. Do not edit.\n\n",
    );

    // Company identifiers.
    let companies = list(
        &root,
        "company_identifiers/company_identifiers.yaml",
        "company_identifiers",
    );
    let mut map = BTreeMap::new();
    for c in &companies {
        map.insert(int(&c["value"]) as u16, string(&c["name"]));
    }
    table_u16(&mut out, "COMPANIES", &map);

    // 16-bit UUIDs, one table per kind.
    for (file, name) in [
        ("uuids/service_uuids.yaml", "SERVICES"),
        ("uuids/characteristic_uuids.yaml", "CHARACTERISTICS"),
        ("uuids/descriptors.yaml", "DESCRIPTORS"),
        ("uuids/declarations.yaml", "DECLARATIONS"),
        ("uuids/units.yaml", "UNITS"),
        ("uuids/member_uuids.yaml", "MEMBERS"),
        ("uuids/sdo_uuids.yaml", "SDOS"),
        ("uuids/service_class.yaml", "SERVICE_CLASSES"),
        ("uuids/protocol_identifiers.yaml", "PROTOCOLS"),
        ("uuids/object_types.yaml", "OBJECT_TYPES"),
        ("uuids/browse_group_identifiers.yaml", "BROWSE_GROUPS"),
        ("uuids/mesh_profile_uuids.yaml", "MESH_PROFILES"),
    ] {
        let entries = list(&root, file, "uuids");
        let mut map: BTreeMap<u16, (String, String)> = BTreeMap::new();
        for e in &entries {
            let id = match &e["id"] {
                Yaml::String(s) => s.clone(),
                _ => String::new(),
            };
            map.insert(int(&e["uuid"]) as u16, (string(&e["name"]), id));
        }
        writeln!(out, "pub(crate) static {name}: &[(u16, &str, &str)] = &[").unwrap();
        for (k, (n, id)) in &map {
            writeln!(out, "    (0x{k:04x}, {n:?}, {id:?}),").unwrap();
        }
        out.push_str("];\n\n");
    }

    // AD types.
    let mut map = BTreeMap::new();
    for e in list(&root, "core/ad_types.yaml", "ad_types") {
        map.insert(int(&e["value"]) as u16, string(&e["name"]));
    }
    table_u16(&mut out, "AD_TYPES", &map);

    // URI schemes (the URI AD type and Eddystone-style compressed URIs).
    let mut map = BTreeMap::new();
    for e in list(&root, "core/uri_schemes.yaml", "uri_schemes") {
        map.insert(int(&e["value"]) as u16, string(&e["name"]));
    }
    table_u16(&mut out, "URI_SCHEMES", &map);

    // Core specification versions (HCI and LMP version numbers).
    let mut map = BTreeMap::new();
    for e in list(&root, "core/core_version.yaml", "core_version") {
        map.insert(int(&e["value"]) as u16, string(&e["name"]));
    }
    table_u16(&mut out, "CORE_VERSIONS", &map);

    // L2CAP PSMs.
    let mut map = BTreeMap::new();
    for e in list(&root, "core/psm.yaml", "psms") {
        map.insert(int(&e["psm"]) as u16, string(&e["name"]));
    }
    table_u16(&mut out, "PSMS", &map);

    // Characteristic Presentation Format types.
    let mut map = BTreeMap::new();
    for e in list(&root, "core/formattypes.yaml", "formattypes") {
        map.insert(
            int(&e["value"]) as u16,
            (string(&e["short_name"]), string(&e["description"])),
        );
    }
    writeln!(
        out,
        "pub(crate) static FORMAT_TYPES: &[(u16, &str, &str)] = &["
    )
    .unwrap();
    for (k, (n, d)) in &map {
        writeln!(out, "    (0x{k:04x}, {n:?}, {d:?}),").unwrap();
    }
    out.push_str("];\n\n");

    // Appearance: 10-bit category, 6-bit subcategory.
    let mut cats = BTreeMap::new();
    let mut subs = BTreeMap::new();
    for c in list(&root, "core/appearance_values.yaml", "appearance_values") {
        let cat = int(&c["category"]) as u16;
        cats.insert(cat, string(&c["name"]));
        if let Yaml::Array(list) = &c["subcategory"] {
            for s in list {
                let v = (cat << 6) | (int(&s["value"]) as u16 & 0x3f);
                subs.insert(v, string(&s["name"]));
            }
        }
    }
    table_u16(&mut out, "APPEARANCE_CATEGORIES", &cats);
    table_u16(&mut out, "APPEARANCE_SUBCATEGORIES", &subs);

    // Mesh opcodes and model identifiers, foundation and models alike.
    let mut ops = BTreeMap::new();
    let mut models = BTreeMap::new();
    let mesh = root.join("mesh");
    let mut files: Vec<_> = fs::read_dir(&mesh)
        .unwrap()
        .flatten()
        .map(|e| e.file_name().into_string().unwrap())
        .collect();
    files.sort();
    for f in files {
        let rel = format!("mesh/{f}");
        if f.ends_with("_opcodes.yaml") && !f.contains("transport_control") {
            for e in list(&root, &rel, "mesh_model_opcodes") {
                ops.insert(int(&e["opcode"]) as u32, string(&e["name"]));
            }
        } else if f.ends_with("_model_uuids.yaml") {
            for e in list(&root, &rel, "mesh_model_uuids") {
                models.insert(int(&e["uuid"]) as u16, string(&e["name"]));
            }
        }
    }
    writeln!(out, "pub(crate) static MESH_OPCODES: &[(u32, &str)] = &[").unwrap();
    for (k, v) in &ops {
        writeln!(out, "    (0x{k:06x}, {v:?}),").unwrap();
    }
    out.push_str("];\n\n");
    table_u16(&mut out, "MESH_MODELS", &models);

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("tables.rs");
    fs::write(dest, out).unwrap();
}

fn list(root: &Path, file: &str, key: &str) -> Vec<Yaml> {
    let text = fs::read_to_string(root.join(file)).unwrap_or_else(|e| panic!("{file}: {e}"));
    let docs = YamlLoader::load_from_str(&text).unwrap_or_else(|e| panic!("{file}: {e}"));
    match &docs[0][key] {
        Yaml::Array(a) => a.clone(),
        other => panic!("{file}: `{key}` is not a list: {other:?}"),
    }
}

fn int(y: &Yaml) -> i64 {
    match y {
        Yaml::Integer(i) => *i,
        Yaml::String(s) | Yaml::Real(s) => {
            let s = s.trim();
            match s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
                Some(h) => i64::from_str_radix(h, 16).unwrap_or_else(|e| panic!("{s}: {e}")),
                None => s.parse().unwrap_or_else(|e| panic!("{s}: {e}")),
            }
        }
        other => panic!("not a number: {other:?}"),
    }
}

fn string(y: &Yaml) -> String {
    match y {
        Yaml::String(s) => s.trim().to_string(),
        Yaml::Integer(i) => i.to_string(),
        Yaml::Real(r) => r.clone(),
        Yaml::Boolean(b) => b.to_string(),
        other => panic!("not a string: {other:?}"),
    }
}

fn table_u16(out: &mut String, name: &str, map: &BTreeMap<u16, String>) {
    writeln!(out, "pub(crate) static {name}: &[(u16, &str)] = &[").unwrap();
    for (k, v) in map {
        writeln!(out, "    (0x{k:04x}, {v:?}),").unwrap();
    }
    out.push_str("];\n\n");
}
